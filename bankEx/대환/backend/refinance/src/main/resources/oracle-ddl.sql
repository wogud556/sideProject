-- 가계대출 대환 업무 시스템 — Oracle DDL (운영 반영용, 수동 실행)
-- 로컬 개발(H2)은 spring.jpa.hibernate.ddl-auto=create-drop 으로 엔티티에서 자동 생성되며,
-- 이 스크립트는 자동 실행되지 않는다. 운영 Oracle DB에는 이 파일 내용을 직접 반영해야 한다.
-- (bankEx의 backend/bankEx/src/main/resources/migration/*.sql 컨벤션과 동일)

CREATE TABLE TB_CUSTOMER (
    CUSTOMER_ID     NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_NO     VARCHAR2(30)  NOT NULL,
    NAME            VARCHAR2(50)  NOT NULL,
    BIRTH_DATE      DATE,
    PHONE           VARCHAR2(20),
    STATUS          VARCHAR2(20)  NOT NULL,
    CONSTRAINT UX_CUSTOMER_NO UNIQUE (CUSTOMER_NO)
);

CREATE TABLE TB_LOAN (
    LOAN_ID                     NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID                 NUMBER(19)     NOT NULL,
    FINANCIAL_INSTITUTION_CODE  VARCHAR2(10)   NOT NULL,
    FINANCIAL_INSTITUTION_NAME  VARCHAR2(50)   NOT NULL,
    LOAN_ACCOUNT_NO             VARCHAR2(30)   NOT NULL,
    LOAN_PRODUCT_CODE           VARCHAR2(30),
    LOAN_PRODUCT_NAME           VARCHAR2(100)  NOT NULL,
    LOAN_TYPE                   VARCHAR2(30)   NOT NULL,
    ORIGINAL_AMOUNT              NUMBER(15,2)  NOT NULL,
    CURRENT_BALANCE              NUMBER(15,2)  NOT NULL,
    INTEREST_RATE                NUMBER(5,2)   NOT NULL,
    EXECUTION_DATE                DATE         NOT NULL,
    MATURITY_DATE                 DATE         NOT NULL,
    REPAYMENT_METHOD             VARCHAR2(30)  NOT NULL,
    OVERDUE_YN                   VARCHAR2(1)   DEFAULT 'N' NOT NULL,
    STATUS                       VARCHAR2(20)  NOT NULL,
    CONSTRAINT FK_LOAN_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES TB_CUSTOMER(CUSTOMER_ID),
    CONSTRAINT UX_LOAN_ACCOUNT_NO UNIQUE (LOAN_ACCOUNT_NO)
);
CREATE INDEX IX_LOAN_CUSTOMER ON TB_LOAN(CUSTOMER_ID);

-- 경량 권한 모델 (명세 31번 축소 구현 — 실제 인증/세션이 아닌 X-Operator-Id 헤더 식별용)
CREATE TABLE TB_REFINANCE_OPERATOR (
    OPERATOR_ID   VARCHAR2(30)  PRIMARY KEY,
    NAME          VARCHAR2(50)  NOT NULL,
    ROLE          VARCHAR2(30)  NOT NULL
);

CREATE TABLE TB_REFINANCE_APPLICATION (
    APPLICATION_ID                    NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_NO                    VARCHAR2(30)  NOT NULL,
    CUSTOMER_ID                       NUMBER(19)    NOT NULL,
    APPLICATION_DATE                  TIMESTAMP     NOT NULL,
    STATUS                            VARCHAR2(30)  NOT NULL,
    REQUESTED_AMOUNT                  NUMBER(15,2)  NOT NULL,
    APPROVED_AMOUNT                   NUMBER(15,2),
    NEW_LOAN_PRODUCT_NAME             VARCHAR2(100),
    NEW_LOAN_AMOUNT                   NUMBER(15,2),
    NEW_LOAN_RATE                     NUMBER(5,2),
    NEW_LOAN_RATE_TYPE                VARCHAR2(20),
    NEW_LOAN_PERIOD_MONTHS            NUMBER(5),
    NEW_LOAN_MATURITY_DATE            DATE,
    NEW_LOAN_REPAYMENT_METHOD         VARCHAR2(30),
    NEW_LOAN_EXECUTION_SCHEDULED_DATE DATE,
    NEW_LOAN_ACCOUNT_NO               VARCHAR2(30),
    REFINANCE_PURPOSE_YN              VARCHAR2(1),
    REJECT_REASON_CODE                VARCHAR2(50),
    CREATED_BY                        VARCHAR2(30),
    CREATED_AT                        TIMESTAMP     NOT NULL,
    UPDATED_BY                        VARCHAR2(30),
    UPDATED_AT                        TIMESTAMP,
    VERSION                           NUMBER(19)    DEFAULT 0 NOT NULL,
    CONSTRAINT UX_REFINANCE_APP_NO UNIQUE (APPLICATION_NO),
    CONSTRAINT FK_REFINANCE_APP_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES TB_CUSTOMER(CUSTOMER_ID)
);
CREATE INDEX IX_REFINANCE_APP_CUSTOMER_STATUS ON TB_REFINANCE_APPLICATION(CUSTOMER_ID, STATUS);
CREATE INDEX IX_REFINANCE_APP_DATE ON TB_REFINANCE_APPLICATION(APPLICATION_DATE);

CREATE TABLE TB_REFINANCE_TARGET (
    TARGET_ID                   NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_ID               NUMBER(19)   NOT NULL,
    LOAN_ID                      NUMBER(19)   NOT NULL,
    FINANCIAL_INSTITUTION_CODE  VARCHAR2(10),
    LOAN_ACCOUNT_NO             VARCHAR2(30)  NOT NULL,
    LOAN_PRODUCT_CODE           VARCHAR2(30),
    LOAN_BALANCE                 NUMBER(15,2),
    REPAYMENT_AMOUNT              NUMBER(15,2),
    PREPAYMENT_FEE                NUMBER(15,2),
    INTEREST_AMOUNT                NUMBER(15,2),
    CONSTRAINT FK_REFINANCE_TARGET_APP FOREIGN KEY (APPLICATION_ID) REFERENCES TB_REFINANCE_APPLICATION(APPLICATION_ID),
    CONSTRAINT FK_REFINANCE_TARGET_LOAN FOREIGN KEY (LOAN_ID) REFERENCES TB_LOAN(LOAN_ID)
);
CREATE INDEX IX_REFINANCE_TARGET_APP ON TB_REFINANCE_TARGET(APPLICATION_ID);

CREATE TABLE TB_REFINANCE_REVIEW (
    REVIEW_ID              NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_ID          NUMBER(19)  NOT NULL,
    REVIEWER_ID             VARCHAR2(30) NOT NULL,
    REVIEWED_AT             TIMESTAMP   NOT NULL,
    ELIGIBILITY_SNAPSHOT    CLOB,
    OPINION                 CLOB,
    CONSTRAINT FK_REFINANCE_REVIEW_APP FOREIGN KEY (APPLICATION_ID) REFERENCES TB_REFINANCE_APPLICATION(APPLICATION_ID)
);
CREATE INDEX IX_REFINANCE_REVIEW_APP ON TB_REFINANCE_REVIEW(APPLICATION_ID);

CREATE TABLE TB_REFINANCE_APPROVAL (
    APPROVAL_ID       NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_ID     NUMBER(19)   NOT NULL,
    DECISION           VARCHAR2(10) NOT NULL,
    APPROVER_ID        VARCHAR2(30) NOT NULL,
    APPROVED_AT        TIMESTAMP    NOT NULL,
    APPROVED_AMOUNT     NUMBER(15,2),
    APPROVAL_CONDITION VARCHAR2(500),
    APPROVAL_MEMO      VARCHAR2(500),
    REJECT_REASON      VARCHAR2(500),
    CONSTRAINT FK_REFINANCE_APPROVAL_APP FOREIGN KEY (APPLICATION_ID) REFERENCES TB_REFINANCE_APPLICATION(APPLICATION_ID)
);
CREATE INDEX IX_REFINANCE_APPROVAL_APP ON TB_REFINANCE_APPROVAL(APPLICATION_ID);

-- REQUEST_ID UNIQUE 제약 = 멱등성 보장 (명세 18번): 동일 거래고유번호로 재요청해도 중복 삽입 불가
CREATE TABLE TB_REFINANCE_TRANSACTION (
    TRANSACTION_ID     NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_ID      NUMBER(19)   NOT NULL,
    TRANSACTION_TYPE    VARCHAR2(30) NOT NULL,
    REQUEST_ID           VARCHAR2(100) NOT NULL,
    TRANSACTION_NO       VARCHAR2(50),
    REQUEST_DATA         CLOB,
    RESPONSE_DATA        CLOB,
    RESULT_CODE          VARCHAR2(20),
    RESULT_MESSAGE       VARCHAR2(500),
    STARTED_AT           TIMESTAMP,
    FINISHED_AT          TIMESTAMP,
    PROCESSED_BY         VARCHAR2(30),
    CONSTRAINT UX_REFINANCE_TXN_REQUEST_ID UNIQUE (REQUEST_ID),
    CONSTRAINT FK_REFINANCE_TXN_APP FOREIGN KEY (APPLICATION_ID) REFERENCES TB_REFINANCE_APPLICATION(APPLICATION_ID)
);
CREATE INDEX IX_REFINANCE_TXN_APP_TYPE ON TB_REFINANCE_TRANSACTION(APPLICATION_ID, TRANSACTION_TYPE);

CREATE TABLE TB_REFINANCE_HISTORY (
    HISTORY_ID       NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_ID     NUMBER(19)  NOT NULL,
    ACTION_TYPE        VARCHAR2(30) NOT NULL,
    FROM_STATUS        VARCHAR2(30),
    TO_STATUS          VARCHAR2(30) NOT NULL,
    DESCRIPTION        VARCHAR2(500),
    PROCESSED_BY       VARCHAR2(30),
    PROCESSED_AT       TIMESTAMP    NOT NULL,
    CONSTRAINT FK_REFINANCE_HISTORY_APP FOREIGN KEY (APPLICATION_ID) REFERENCES TB_REFINANCE_APPLICATION(APPLICATION_ID)
);
CREATE INDEX IX_REFINANCE_HISTORY_APP ON TB_REFINANCE_HISTORY(APPLICATION_ID, PROCESSED_AT);

CREATE TABLE TB_REFINANCE_ERROR (
    ERROR_ID         NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_ID     NUMBER(19)  NOT NULL,
    TRANSACTION_ID     NUMBER(19),
    FAILED_STEP        VARCHAR2(30) NOT NULL,
    ERROR_CODE         VARCHAR2(30),
    ERROR_MESSAGE      VARCHAR2(500),
    STATUS             VARCHAR2(30) NOT NULL,
    RETRY_COUNT        NUMBER(5)    DEFAULT 0,
    CREATED_AT         TIMESTAMP    NOT NULL,
    UPDATED_AT         TIMESTAMP,
    CONSTRAINT FK_REFINANCE_ERROR_APP FOREIGN KEY (APPLICATION_ID) REFERENCES TB_REFINANCE_APPLICATION(APPLICATION_ID),
    CONSTRAINT FK_REFINANCE_ERROR_TXN FOREIGN KEY (TRANSACTION_ID) REFERENCES TB_REFINANCE_TRANSACTION(TRANSACTION_ID)
);
CREATE INDEX IX_REFINANCE_ERROR_APP ON TB_REFINANCE_ERROR(APPLICATION_ID);
CREATE INDEX IX_REFINANCE_ERROR_STATUS ON TB_REFINANCE_ERROR(STATUS);

CREATE TABLE TB_AUDIT_LOG (
    AUDIT_ID       NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OPERATOR_ID     VARCHAR2(30) NOT NULL,
    ACTION_TYPE     VARCHAR2(30) NOT NULL,
    CUSTOMER_ID     NUMBER(19),
    APPLICATION_ID  NUMBER(19),
    DESCRIPTION     VARCHAR2(500),
    CREATED_AT      TIMESTAMP    NOT NULL
);
CREATE INDEX IX_AUDIT_LOG_CREATED_AT ON TB_AUDIT_LOG(CREATED_AT);
CREATE INDEX IX_AUDIT_LOG_APPLICATION ON TB_AUDIT_LOG(APPLICATION_ID);
