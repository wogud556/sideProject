-- 여신(대출) 도메인 MyBatis 전환에 따른 테이블 정의.
-- Spring Boot는 내장 DB(H2)에 한해서만 앱 시작 시 이 스크립트를 자동 실행한다.
-- Oracle 운영 환경은 자동 실행되지 않으므로, 이 파일 내용을 그대로 운영 DB에 수동으로 반영해야 한다.

CREATE TABLE LOAN_PRODUCT (
    PRODUCT_ID     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_NAME   VARCHAR(100) NOT NULL,
    INTEREST_RATE  NUMBER(5,2),
    MAX_LIMIT      NUMBER(15),
    DESCRIPTION    VARCHAR(500)
);

CREATE TABLE LOAN_APPLICATION (
    APPLICATION_ID     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID            VARCHAR(50) NOT NULL,
    ACCOUNT_NUMBER     VARCHAR(20) NOT NULL,
    PRODUCT_ID         NUMBER(19) NOT NULL,
    REQUEST_AMOUNT     NUMBER(15) NOT NULL,
    LOAN_PERIOD        NUMBER(5) NOT NULL,
    STATUS             VARCHAR(20),
    REMAINING_BALANCE  NUMBER(15),
    CREATED_AT         TIMESTAMP
);

CREATE TABLE JEONSE_LOAN_PRODUCT (
    PRODUCT_ID        VARCHAR(30) PRIMARY KEY,
    PRODUCT_NAME      VARCHAR(100) NOT NULL,
    PRODUCT_TYPE      VARCHAR(30) NOT NULL,
    MAX_LIMIT_AMOUNT  NUMBER(15) NOT NULL,
    BASE_RATE         NUMBER(5,2) NOT NULL,
    MIN_RATE          NUMBER(5,2),
    MAX_RATE          NUMBER(5,2),
    USE_YN            VARCHAR(1) DEFAULT 'Y',
    CREATED_AT        TIMESTAMP
);

CREATE TABLE JEONSE_LOAN_APPLICATION (
    APPLICATION_ID        VARCHAR(40) PRIMARY KEY,
    USER_ID               VARCHAR(50) NOT NULL,
    PRODUCT_ID            VARCHAR(30) NOT NULL,
    REQUEST_AMOUNT        NUMBER(15) NOT NULL,
    AVAILABLE_LIMIT_AMOUNT NUMBER(15),
    APPROVED_AMOUNT       NUMBER(15),
    ANNUAL_INCOME         NUMBER(15) NOT NULL,
    EXISTING_DEBT_AMOUNT  NUMBER(15) DEFAULT 0,
    CREDIT_SCORE          NUMBER(4) NOT NULL,
    HOMELESS_YN           VARCHAR(1) NOT NULL,
    HOUSEHOLDER_YN        VARCHAR(1) NOT NULL,
    GUARANTEE_ORG         VARCHAR(10) NOT NULL,
    REPAYMENT_TYPE        VARCHAR(30) NOT NULL,
    LOAN_RATE             NUMBER(5,2),
    STATUS                VARCHAR(30) NOT NULL,
    REJECT_REASON_CODE    VARCHAR(50),
    CREATED_AT            TIMESTAMP,
    UPDATED_AT            TIMESTAMP
);

CREATE TABLE JEONSE_CONTRACT (
    CONTRACT_ID          VARCHAR(40) PRIMARY KEY,
    APPLICATION_ID       VARCHAR(40) NOT NULL,
    LESSOR_NAME          VARCHAR(100) NOT NULL,
    LESSOR_PHONE         VARCHAR(30),
    HOUSE_ADDRESS        VARCHAR(300) NOT NULL,
    HOUSE_TYPE           VARCHAR(30) NOT NULL,
    CAPITAL_AREA_YN      VARCHAR(1) NOT NULL,
    DEPOSIT_AMOUNT       NUMBER(15) NOT NULL,
    DOWN_PAYMENT_AMOUNT  NUMBER(15) NOT NULL,
    CONTRACT_START_DATE  DATE NOT NULL,
    CONTRACT_END_DATE    DATE NOT NULL,
    FIXED_DATE_YN        VARCHAR(1) DEFAULT 'N',
    MOVE_IN_PLAN_YN      VARCHAR(1) DEFAULT 'N',
    SENIOR_CLAIM_AMOUNT  NUMBER(15) DEFAULT 0,
    CREATED_AT           TIMESTAMP
);

CREATE TABLE LOAN_REPAYMENT_SCHEDULE (
    SCHEDULE_ID        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_ID     VARCHAR(40) NOT NULL,
    PAYMENT_SEQ        NUMBER(5) NOT NULL,
    PAYMENT_DATE       DATE NOT NULL,
    PRINCIPAL_AMOUNT   NUMBER(15) DEFAULT 0,
    INTEREST_AMOUNT    NUMBER(15) DEFAULT 0,
    TOTAL_AMOUNT       NUMBER(15) DEFAULT 0,
    PAID_YN            VARCHAR(1) DEFAULT 'N',
    CREATED_AT         TIMESTAMP
);

-- deposit.savings (적금) 도메인 테이블

CREATE TABLE SAVINGS_PRODUCT (
    PRODUCT_ID        VARCHAR(30) PRIMARY KEY,
    PRODUCT_NAME      VARCHAR(100) NOT NULL,
    BASE_RATE         NUMBER(5,2) NOT NULL,
    MAX_RATE          NUMBER(5,2) NOT NULL,
    MIN_AMOUNT        NUMBER(15) NOT NULL,
    MAX_AMOUNT        NUMBER(15) NOT NULL,
    PERIOD            NUMBER(3) NOT NULL,
    AUTO_TRANSFER_YN  VARCHAR(1) DEFAULT 'Y',
    STATUS            VARCHAR(20) NOT NULL,
    CREATED_AT        TIMESTAMP
);

CREATE TABLE SAVINGS_ACCOUNT (
    ACCOUNT_NO           VARCHAR(20) PRIMARY KEY,
    USER_ID              VARCHAR(50) NOT NULL,
    PRODUCT_ID           VARCHAR(30) NOT NULL,
    WITHDRAW_ACCOUNT_NO  VARCHAR(20) NOT NULL,
    MONTHLY_AMOUNT       NUMBER(15) NOT NULL,
    PERIOD               NUMBER(3) NOT NULL,
    CURRENT_COUNT        NUMBER(3) DEFAULT 0,
    BALANCE              NUMBER(15) DEFAULT 0,
    INTEREST_RATE        NUMBER(5,2) NOT NULL,
    STATUS               VARCHAR(20) NOT NULL,
    OPEN_DATE            DATE NOT NULL,
    MATURITY_DATE        DATE NOT NULL,
    CREATED_AT           TIMESTAMP,
    UPDATED_AT           TIMESTAMP
);

CREATE TABLE SAVINGS_PAYMENT_HISTORY (
    PAYMENT_ID       NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_NO       VARCHAR(20) NOT NULL,
    PAYMENT_SEQ      NUMBER(3) NOT NULL,
    PAYMENT_DATE     DATE NOT NULL,
    PAYMENT_AMOUNT   NUMBER(15) NOT NULL,
    STATUS           VARCHAR(20) NOT NULL,
    CREATED_AT       TIMESTAMP
);

CREATE TABLE AUTO_TRANSFER (
    AUTO_ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_NO         VARCHAR(20) NOT NULL,
    WITHDRAW_ACCOUNT   VARCHAR(20) NOT NULL,
    TRANSFER_DAY       NUMBER(2) NOT NULL,
    STATUS             VARCHAR(20) NOT NULL,
    CREATED_AT         TIMESTAMP
);
